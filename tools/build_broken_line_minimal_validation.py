def load_matrix(path: Path) -> np.ndarray | None:
    if not path.exists() or path.stat().st_size == 0:
        return None
    data = np.loadtxt(path)
    if data.ndim == 1:
        data = data[np.newaxis, :]
    return data


def split_node_record(data: np.ndarray, n_nodes: int) -> tuple[np.ndarray, np.ndarray]:
    if data.shape[1] == 3 * n_nodes + 1:
        return data[:, 0], data[:, 1:]
    return np.arange(data.shape[0]) * 0.05, data


def export_records(source: str, raw_dir: Path, out_dir: Path) -> dict[str, Any]:
    out_dir.mkdir(parents=True, exist_ok=True)
    dyn_raw = load_matrix(raw_dir / "Dynamic.out")
    if dyn_raw is None:
        raise FileNotFoundError(raw_dir / "Dynamic.out")
    time, dyn = split_node_record(dyn_raw, N_NODES)
    n = len(time)

    records: dict[str, Any] = {
        "source": source,
        "time": time,
        "disp": dyn.reshape(n, N_NODES, 3),
        "velocity": None,
        "accel": None,
        "reaction": None,
        "damping": None,
    }

    for stem, key in [("Velocity.out", "velocity"), ("Accel.out", "accel")]:
        raw = load_matrix(raw_dir / stem)
        if raw is not None:
            _, values = split_node_record(raw, N_NODES)
            records[key] = values.reshape(values.shape[0], N_NODES, 3)

    reaction_raw = load_matrix(raw_dir / "Reaction.out")
    if reaction_raw is not None:
        records["reaction"] = reaction_raw[:, -3:]

    damping_raw = load_matrix(raw_dir / "damping_change_log.txt")
    if damping_raw is not None:
        records["damping"] = damping_raw

    fields = ["time_s"]
    for node in range(1, N_NODES + 1):
        for comp in ["x", "y", "z"]:
            fields.append(f"node{node}_disp_{comp}_m")
    rows = []
    for i, t in enumerate(time):
        row = {"time_s": float(t)}
        for node in range(N_NODES):
            for j, comp in enumerate(["x", "y", "z"]):
                row[f"node{node+1}_disp_{comp}_m"] = float(records["disp"][i, node, j])
        rows.append(row)
    write_csv(out_dir / "all_node_displacement.csv", rows, fields)

    for key, filename, unit in [
        ("velocity", "all_node_velocity.csv", "mps"),
        ("accel", "all_node_acceleration.csv", "mps2"),
    ]:
        arr = records[key]
        if arr is None:
            continue
        fields = ["time_s"]
        for node in range(1, N_NODES + 1):
            for comp in ["x", "y", "z"]:
                fields.append(f"node{node}_{key}_{comp}_{unit}")
        rows = []
        for i, t in enumerate(time[: arr.shape[0]]):
            row = {"time_s": float(t)}
            for node in range(N_NODES):
                for j, comp in enumerate(["x", "y", "z"]):
                    row[f"node{node+1}_{key}_{comp}_{unit}"] = float(arr[i, node, j])
            rows.append(row)
        write_csv(out_dir / filename, rows, fields)

    if records["reaction"] is not None:
        write_csv(
            out_dir / "support_reaction_node1.csv",
            [{"time_s": float(time[i]), "Rx_N": float(v[0]), "Ry_N": float(v[1]), "Rz_N": float(v[2])} for i, v in enumerate(records["reaction"][: len(time)])],
            ["time_s", "Rx_N", "Ry_N", "Rz_N"],
        )
    if records["damping"] is not None:
        fields = ["time_s", "element", "previous_xi", "xi_total"]
        rows = []
        for row in records["damping"]:
            rows.append({field: float(row[i]) for i, field in enumerate(fields[: min(len(fields), len(row))])})
        write_csv(out_dir / "damping_change_log.csv", rows, fields[: records["damping"].shape[1]])

    summary = {
        "source": source,
        "rows_dynamic": int(n),
        "time_start": float(time[0]),
        "time_end": float(time[-1]),
        "has_velocity": records["velocity"] is not None,
        "has_accel": records["accel"] is not None,
        "has_damping": records["damping"] is not None,
        "middle_node_max_abs_disp": {
            "x": float(np.max(np.abs(records["disp"][:, MONITOR_NODE - 1, 0]))),
            "y": float(np.max(np.abs(records["disp"][:, MONITOR_NODE - 1, 1]))),
            "z": float(np.max(np.abs(records["disp"][:, MONITOR_NODE - 1, 2]))),
        },
    }
    (out_dir / "summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    records["summary"] = summary
    return records


def write_csv(path: Path, rows: list[dict[str, Any]], fields: list[str]) -> None:
    with path.open("w", newline="", encoding="utf-8-sig") as f:
        writer = csv.DictWriter(f, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)


def plot_center_response(path: Path, py: dict[str, Any], mat: dict[str, Any], key: str, ylabel: str) -> None:
    py_arr = py[key]
    mat_arr = mat[key]
    if py_arr is None or mat_arr is None:
        return
    fig, axes = plt.subplots(2, 2, figsize=(13.0, 8.0), dpi=170)
    axes = axes.ravel()
    comps = [("x", 0), ("y", 1), ("z", 2)]
    for comp, idx in comps:
        axes[0].plot(py["time"][: py_arr.shape[0]], py_arr[:, MONITOR_NODE - 1, idx], lw=1.0, label=f"Python {comp}")
        axes[0].plot(mat["time"][: mat_arr.shape[0]], mat_arr[:, MONITOR_NODE - 1, idx], lw=0.85, ls="--", label=f"MATLAB {comp}")
    axes[0].set_title("Middle node: x/y/z")
    axes[0].legend(fontsize=7, ncol=2)
    for ax, (comp, idx) in zip(axes[1:], comps):
        ax.plot(py["time"][: py_arr.shape[0]], py_arr[:, MONITOR_NODE - 1, idx], lw=1.05, label="Python")
        ax.plot(mat["time"][: mat_arr.shape[0]], mat_arr[:, MONITOR_NODE - 1, idx], lw=0.9, ls="--", label="MATLAB")
        ax.set_title(f"Middle node {comp}")
        ax.legend(fontsize=8)
    for ax in axes:
        ax.grid(True, color="#D8DEE8", lw=0.6)
        ax.set_xlabel("Time (s)")
        ax.set_ylabel(ylabel)
    fig.suptitle(f"Broken-line 3-node minimal model: {key}", fontsize=14, weight="bold")
    fig.tight_layout(rect=[0, 0, 1, 0.95])
    fig.savefig(path)
    plt.close(fig)


def plot_xz(path: Path, records: dict[str, Any], title: str) -> None:
    disp = records["disp"]
    time = records["time"]
    idx = MONITOR_NODE - 1
    fig, ax = plt.subplots(figsize=(7.2, 6.0), dpi=170, layout="constrained")
    sc = ax.scatter(disp[:, idx, 0], disp[:, idx, 2], c=time, s=5, cmap="viridis", alpha=0.85)
    ax.plot(disp[:, idx, 0], disp[:, idx, 2], color="#1E252D", lw=0.35, alpha=0.45)
    ax.set_title(title)
    ax.set_xlabel("x horizontal disp (m)")
    ax.set_ylabel("z vertical disp (m)")
    ax.grid(True, color="#D8DEE8", lw=0.6)
    ax.axis("equal")
    fig.colorbar(sc, ax=ax, label="Time (s)")
    fig.savefig(path)
    plt.close(fig)


def compare_records(py: dict[str, Any], mat: dict[str, Any]) -> list[dict[str, Any]]:
    t_end = min(float(py["time"][-1]), float(mat["time"][-1]))
    t_start = max(float(py["time"][0]), float(mat["time"][0]))
    common_t = np.arange(t_start, t_end + 1e-9, 0.05)
    rows = []
    units = {"disp": "m", "velocity": "mps", "accel": "mps2"}
    for key in ["disp", "velocity", "accel"]:
        if py[key] is None or mat[key] is None:
            continue
        for node in range(N_NODES):
            for comp, idx in [("x", 0), ("y", 1), ("z", 2)]:
                py_v = np.interp(common_t, py["time"][: py[key].shape[0]], py[key][:, node, idx])
                mat_v = np.interp(common_t, mat["time"][: mat[key].shape[0]], mat[key][:, node, idx])
                rows.append({
                    "record": key,
                    "location": f"node_{node + 1}",
                    "component": comp,
                    "unit": units[key],
                    "common_time_end_s": t_end,
                    "python_max_abs": float(np.max(np.abs(py_v))),
                    "matlab_max_abs": float(np.max(np.abs(mat_v))),
                    "rms_diff": float(np.sqrt(np.mean((py_v - mat_v) ** 2))),
                    "max_abs_diff": float(np.max(np.abs(py_v - mat_v))),
                })
    if py["reaction"] is not None and mat["reaction"] is not None:
        n = min(py["reaction"].shape[0], mat["reaction"].shape[0], len(common_t))
        for comp, idx in [("Rx", 0), ("Ry", 1), ("Rz", 2)]:
            py_v = py["reaction"][:n, idx]
            mat_v = mat["reaction"][:n, idx]
            rows.append({
                "record": "reaction",
                "location": "support_node_1",
                "component": comp,
                "unit": "N",
                "common_time_end_s": float(common_t[n - 1]) if n else t_end,
                "python_max_abs": float(np.max(np.abs(py_v))),
                "matlab_max_abs": float(np.max(np.abs(mat_v))),
                "rms_diff": float(np.sqrt(np.mean((py_v - mat_v) ** 2))),
                "max_abs_diff": float(np.max(np.abs(py_v - mat_v))),
            })
    if py["damping"] is not None and mat["damping"] is not None:
        n = min(py["damping"].shape[0], mat["damping"].shape[0])
        for name, idx in [("element", 1), ("previous_xi", 2), ("xi_total", 3)]:
            if idx >= py["damping"].shape[1] or idx >= mat["damping"].shape[1]:
                continue
            py_v = py["damping"][:n, idx]
            mat_v = mat["damping"][:n, idx]
            rows.append({
                "record": "damping_log",
                "location": "all_logged_elements",
                "component": name,
                "unit": "-",
                "common_time_end_s": float(min(py["damping"][n - 1, 0], mat["damping"][n - 1, 0])) if n else t_end,
                "python_max_abs": float(np.max(np.abs(py_v))),
                "matlab_max_abs": float(np.max(np.abs(mat_v))),
                "rms_diff": float(np.sqrt(np.mean((py_v - mat_v) ** 2))),
                "max_abs_diff": float(np.max(np.abs(py_v - mat_v))),
            })
    return rows


