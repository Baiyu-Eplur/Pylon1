def postprocess() -> None:
    POST_DIR.mkdir(parents=True, exist_ok=True)
    py = export_records("python", PY_DIR, PY_DIR / "minimal_outputs")
    mat = export_records("matlab", MAT_WORK / "Output", MAT_DIR / "minimal_outputs")
    compare_rows = compare_records(py, mat)
    write_csv(POST_DIR / "python_matlab_minimal_comparison.csv", compare_rows, list(compare_rows[0].keys()))
    write_csv(POST_DIR / "python_matlab_all_record_comparison.csv", compare_rows, list(compare_rows[0].keys()))
    plot_center_response(POST_DIR / "middle_node_displacement_comparison.png", py, mat, "disp", "displacement (m)")
    plot_center_response(POST_DIR / "middle_node_velocity_comparison.png", py, mat, "velocity", "velocity (m/s)")
    plot_center_response(POST_DIR / "middle_node_acceleration_comparison.png", py, mat, "accel", "acceleration (m/s^2)")
    plot_xz(PY_DIR / "minimal_outputs" / "middle_node_xz_trajectory.png", py, "Python: middle-node x-z trajectory")
    plot_xz(MAT_DIR / "minimal_outputs" / "middle_node_xz_trajectory.png", mat, "MATLAB: middle-node x-z trajectory")
    write_report(compare_rows, py, mat)
    (POST_DIR / "validation_manifest.json").write_text(json.dumps({
        "validation_root": str(VALIDATION_ROOT),
        "python_output": str(PY_DIR),
        "matlab_output": str(MAT_DIR),
        "comparison_output": str(POST_DIR),
        "model": "broken-line minimal 3-node",
        "monitor_node": MONITOR_NODE,
    }, indent=2), encoding="utf-8")


