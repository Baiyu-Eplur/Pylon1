def as_posix(path: Path) -> str:
    return str(path.resolve()).replace("\\", "/")


def prepare_python_config(npt: int = 4096) -> Path:
    cfg = load_config(ROOT / "config" / "timur_baseline.yaml")
    cfg["time_history"]["npt"] = npt
    cfg["time_history"]["folder_1"] = ["FORCE_3"]
    cfg["time_history"]["folder_2"] = ["SIM1"]
    cfg["wind_generation"]["enabled"] = False
    cfg["paths"]["output_dir"] = as_posix(PY_DIR)
    cfg["paths"]["save_prefix"] = "PY_FORCE3_BASELINE"
    cfg["solver"]["opensees_path"] = as_posix(Path(cfg["solver"]["opensees_path"]))
    cfg["solver"]["input_tcl"] = as_posix(PY_DIR / "Input.tcl")
    cfg["solver"]["work_dir"] = as_posix(ROOT)
    cfg["display"]["plotter"] = False
    cfg["display"]["modal_plotter"] = False
    cfg["display"]["realtime_monitor"] = False
    CASE_CONFIG.parent.mkdir(parents=True, exist_ok=True)
    dump_config(cfg, CASE_CONFIG)
    return CASE_CONFIG


