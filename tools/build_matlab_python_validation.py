    py = export_timeseries("python", PY_DIR, PY_DIR / "three_point_outputs")
    mat_output = MAT_WORK / "Output"
    mat = export_timeseries("matlab", mat_output, MAT_DIR / "three_point_outputs")

    for source, data, out in [("python", py, PY_DIR), ("matlab", mat, MAT_DIR)]:
        t = data["time"]
        quad_timeseries_plot(out / "three_point_outputs" / "disp_x_quad.png", f"{source}: horizontal displacement", t, {l: data["disp_y"][:, node - 1] for l, _, node in MONITORS}, "disp x/y (m)")
        quad_timeseries_plot(out / "three_point_outputs" / "disp_z_quad.png", f"{source}: vertical displacement", t, {l: data["disp_z"][:, node - 1] for l, _, node in MONITORS}, "disp z (m)")
        coeff_t, _, _, _ = coeff_histories(4096)
        quad_timeseries_plot(out / "three_point_outputs" / "cd_quad.png", f"{source}: C_D", coeff_t, data["cd"], "C_D")
        quad_timeseries_plot(out / "three_point_outputs" / "cl_quad.png", f"{source}: C_L", coeff_t, data["cl"], "C_L")
        quad_timeseries_plot(out / "three_point_outputs" / "delta_d_quad.png", f"{source}: Den Hartog delta_D", coeff_t, data["delta"], "delta_D")
        if len(data["damp_t"]):
            quad_timeseries_plot(out / "three_point_outputs" / "damping_quad.png", f"{source}: effective damping", data["damp_t"], data["damp"], "xi_total")
        trajectory_plot(out / "three_point_outputs" / "xz_trajectory.png", data, f"{source}: x-z displacement trajectory")

    compare_rows = []
    for label, name, node_id in MONITORS:
        idx = node_id - 1
        t_end = min(float(py["time"][-1]), float(mat["time"][-1]))
        common_t = np.arange(max(float(py["time"][0]), float(mat["time"][0])), t_end + 1e-9, 0.05)
        py_x = np.interp(common_t, py["time"], py["disp_y"][:, idx])
        py_z = np.interp(common_t, py["time"], py["disp_z"][:, idx])
        mat_x = np.interp(common_t, mat["time"], mat["disp_y"][:, idx])
        mat_z = np.interp(common_t, mat["time"], mat["disp_z"][:, idx])
        early = common_t <= 120.0
        compare_rows.append({
            "monitor": name,
            "node": node_id,
            "common_time_end_s": t_end,
            "python_end_s": float(py["time"][-1]),
            "matlab_end_s": float(mat["time"][-1]),
            "python_max_abs_x_common": float(np.max(np.abs(py_x))),
            "matlab_max_abs_x_common": float(np.max(np.abs(mat_x))),
            "python_max_abs_z_common": float(np.max(np.abs(py_z))),
            "matlab_max_abs_z_common": float(np.max(np.abs(mat_z))),
            "rms_diff_x_common": float(np.sqrt(np.mean((py_x - mat_x) ** 2))),
            "rms_diff_z_common": float(np.sqrt(np.mean((py_z - mat_z) ** 2))),
            "rms_diff_x_0_120s": float(np.sqrt(np.mean((py_x[early] - mat_x[early]) ** 2))),
            "rms_diff_z_0_120s": float(np.sqrt(np.mean((py_z[early] - mat_z[early]) ** 2))),
        })
    write_csv(POST_DIR / "python_matlab_three_point_comparison.csv", compare_rows, list(compare_rows[0].keys()))
    write_validation_report(compare_rows, py, mat)
    (POST_DIR / "validation_manifest.json").write_text(json.dumps({
        "validation_root": str(VALIDATION_ROOT),
        "python_output": str(PY_DIR),
        "matlab_output": str(MAT_DIR),
        "comparison_output": str(POST_DIR),
        "monitors": MONITORS,
    }, indent=2), encoding="utf-8")


