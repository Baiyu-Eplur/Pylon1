def load_dynamic(output_dir: Path, n_nodes: int) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    data = np.loadtxt(output_dir / "Dynamic.out")
    if data.ndim == 1:
        data = data[np.newaxis, :]
    if data.shape[1] == 3 * n_nodes + 1:
        time = data[:, 0]
        arr = data[:, 1:]
    else:
        time = np.arange(data.shape[0]) * 0.05
        arr = data
    return time, arr[:, 0::3], arr[:, 1::3], arr[:, 2::3]


def load_velocity(output_dir: Path, n_nodes: int) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray] | None:
    path = output_dir / "Velocity.out"
    if not path.exists():
        return None
    data = np.loadtxt(path)
    if data.ndim == 1:
        data = data[np.newaxis, :]
    if data.shape[1] == 3 * n_nodes + 1:
        time = data[:, 0]
        arr = data[:, 1:]
    else:
        time = np.arange(data.shape[0]) * 0.05
        arr = data
    return time, arr[:, 0::3], arr[:, 1::3], arr[:, 2::3]


def read_vec(path: Path, n: int | None = None) -> np.ndarray:
    values = np.loadtxt(path)
    return values[:n] if n is not None else values


def damping_by_monitor(output_dir: Path) -> tuple[np.ndarray, dict[str, np.ndarray]]:
    path = output_dir / "damping_change_log.txt"
    if not path.exists():
        return np.array([]), {label: np.array([]) for label, _, _ in MONITORS}
    data = np.loadtxt(path)
    if data.ndim == 1:
        data = data[np.newaxis, :]
    times = np.unique(np.round(data[:, 0], 8))
    result: dict[str, np.ndarray] = {}
    for label, _, node_id in MONITORS:
        idx = node_id - 1
        elems = []
        if idx > 0:
            elems.append(idx)
        if idx < 100:
            elems.append(idx + 1)
        values = np.full(len(times), np.nan)
        for i, t in enumerate(times):
            mask = (np.round(data[:, 0], 8) == t) & np.isin(data[:, 1].astype(int), elems)
            if np.any(mask):
                values[i] = np.mean(data[mask, 3])
        result[label] = values
    return times, result


def coeff_histories(n_steps: int) -> tuple[np.ndarray, dict[str, np.ndarray], dict[str, np.ndarray], dict[str, np.ndarray]]:
    time = read_vec(ROOT / "data" / "aero_coeffs" / "time.txt", n_steps)
    cd_table = _load_coefficient_table(ROOT / "data" / "aero_coeffs" / "C_D_data.txt")
    cl_table = _load_coefficient_table(ROOT / "data" / "aero_coeffs" / "C_L_data2.txt")
    dcl = np.loadtxt(ROOT / "data" / "aero_coeffs" / "dC_L.txt")
    cd: dict[str, np.ndarray] = {}
    cl: dict[str, np.ndarray] = {}
    delta: dict[str, np.ndarray] = {}
    for label, _, node_id in MONITORS:
        u = read_vec(ROOT / "data" / "forces" / "FORCE_3" / "SIM1" / f"NODE_{node_id}_wind_H.txt", n_steps)
        w = read_vec(ROOT / "data" / "forces" / "FORCE_3" / "SIM1" / f"NODE_{node_id}_wind_V.txt", n_steps)
        alpha = np.abs(np.rad2deg(np.arctan2(w, u)))
        cd[label] = _linear_extrapolate(alpha, cd_table[:, 0], cd_table[:, 1])
        cl[label] = _linear_extrapolate(alpha, cl_table[:, 0], cl_table[:, 1])
        delta[label] = cd[label] + _linear_extrapolate(alpha, cd_table[:, 0], dcl) * 180.0 / math.pi
    return time, cd, cl, delta


def export_timeseries(source: str, output_dir: Path, out_dir: Path) -> dict[str, Any]:
    cfg = load_config(CASE_CONFIG)
    geo = CableGeometry(cfg).generate()
    n_nodes = len(geo["x"])
    time, dx, dy, dz = load_dynamic(output_dir, n_nodes)
    n = len(time)
    coeff_time, cd, cl, delta = coeff_histories(min(n, 4096))
    damp_t, damp = damping_by_monitor(output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    rows: list[dict[str, Any]] = []
    fields = ["time_s"]
    for label, _, node_id in MONITORS:
        fields.extend([f"{label}_disp_x_m", f"{label}_disp_z_m"])
    for i, t in enumerate(time):
        row: dict[str, Any] = {"time_s": float(t)}
        for label, _, node_id in MONITORS:
            idx = node_id - 1
            row[f"{label}_disp_x_m"] = float(dy[i, idx])
            row[f"{label}_disp_z_m"] = float(dz[i, idx])
        rows.append(row)
    write_csv(out_dir / "three_point_displacement.csv", rows, fields)

    crows: list[dict[str, Any]] = []
    cfields = ["time_s"]
    for label, _, _ in MONITORS:
        cfields.extend([f"{label}_C_D", f"{label}_C_L", f"{label}_delta_D"])
    for i, t in enumerate(coeff_time):
        row = {"time_s": float(t)}
        for label, _, _ in MONITORS:
            row[f"{label}_C_D"] = float(cd[label][i])
            row[f"{label}_C_L"] = float(cl[label][i])
            row[f"{label}_delta_D"] = float(delta[label][i])
        crows.append(row)
    write_csv(out_dir / "three_point_aero_coeff_delta.csv", crows, cfields)

    drows: list[dict[str, Any]] = []
    dfields = ["time_s"] + [f"{label}_xi_mean" for label, _, _ in MONITORS]
    for i, t in enumerate(damp_t):
        row = {"time_s": float(t)}
        for label, _, _ in MONITORS:
            row[f"{label}_xi_mean"] = None if np.isnan(damp[label][i]) else float(damp[label][i])
        drows.append(row)
    write_csv(out_dir / "three_point_damping.csv", drows, dfields)

    summary = {
        "source": source,
        "rows_dynamic": n,
        "time_start": float(time[0]),
        "time_end": float(time[-1]),
        "has_velocity": (output_dir / "Velocity.out").exists(),
    }
    (out_dir / "summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    return {"time": time, "disp_y": dy, "disp_z": dz, "cd": cd, "cl": cl, "delta": delta, "damp_t": damp_t, "damp": damp, "geo": geo}


def write_csv(path: Path, rows: list[dict[str, Any]], fields: list[str]) -> None:
    with path.open("w", newline="", encoding="utf-8-sig") as f:
        writer = csv.DictWriter(f, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)


def quad_timeseries_plot(path: Path, title: str, time: np.ndarray, series: dict[str, np.ndarray], ylabel: str) -> None:
    fig, axes = plt.subplots(2, 2, figsize=(13.5, 8.2), dpi=170, sharex=False)
    axes = axes.ravel()
    colors = {"quarter_1": "#2E74B5", "midspan": "#4A8F5A", "quarter_3": "#C7832B"}
    names = {"quarter_1": "1/4 span", "midspan": "Midspan", "quarter_3": "3/4 span"}
    for label in ["quarter_1", "midspan", "quarter_3"]:
        axes[0].plot(time[: len(series[label])], series[label], lw=1.05, label=names[label], color=colors[label])
    axes[0].set_title("Three-point comparison")
    axes[0].legend(fontsize=8)
    for ax, label in zip(axes[1:], ["quarter_1", "midspan", "quarter_3"]):
        ax.plot(time[: len(series[label])], series[label], lw=1.05, color=colors[label])
        ax.set_title(names[label])
    for ax in axes:
        ax.grid(True, color="#D8DEE8", lw=0.6)
        ax.set_xlabel("Time (s)")
        ax.set_ylabel(ylabel)
    fig.suptitle(title, fontsize=15, weight="bold")
    fig.tight_layout(rect=[0, 0, 1, 0.96])
    fig.savefig(path)
    plt.close(fig)


def trajectory_plot(path: Path, data: dict[str, Any], title: str, max_points: int = 2200) -> None:
    time = data["time"]
    dy = data["disp_y"]
    dz = data["disp_z"]
    if len(time) > max_points:
        idxs = np.linspace(0, len(time) - 1, max_points).astype(int)
    else:
        idxs = np.arange(len(time))
    fig, axes = plt.subplots(1, 3, figsize=(16.2, 4.9), dpi=170, layout="constrained")
    for ax, (_, name, node_id) in zip(axes, MONITORS):
        idx = node_id - 1
        sc = ax.scatter(dy[idxs, idx], dz[idxs, idx], c=time[idxs], s=5, cmap="viridis", alpha=0.85)
        ax.plot(dy[idxs, idx], dz[idxs, idx], color="#1E252D", lw=0.35, alpha=0.45)
        ax.set_title(f"{name} (Node {node_id})")
        ax.set_xlabel("x/y horizontal disp (m)")
        ax.set_ylabel("z vertical disp (m)")
        ax.grid(True, color="#D8DEE8", lw=0.6)
        ax.axis("equal")
    fig.colorbar(sc, ax=axes.tolist(), label="Time (s)", shrink=0.86, pad=0.02)
    fig.suptitle(title, fontsize=15, weight="bold")
    fig.savefig(path)
    plt.close(fig)


